    for row in rows:
        if row["section"] not in seen:
            seen.append(row["section"])
    body = []
    for section in seen:
        body.append(f'<tr class="sec"><td colspan="14">{html.escape(section)}</td></tr>')
        body += [build_row(r, floor) for r in rows if r["section"] == section]

