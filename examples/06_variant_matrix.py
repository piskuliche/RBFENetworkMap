def graph_metrics(net_path: Path) -> dict:
    """Return bridge count, cycle coverage and soft-core uniformity for a network.

    Parameters
    ----------
    net_path
        Path to a network JSON file written by ``rbfenet plan``.

    Returns
    -------
    dict
        Metrics ``diagnose`` does not itself report. ``n_nonuniform_softcore`` counts
        ligands carrying more than one distinct soft-core mask across their edges --
        each of those needs a different Amber ``scmask`` per edge.
    """
    net = json.loads(net_path.read_text())
    graph = nx.Graph()
    graph.add_nodes_from(lig["name"] for lig in net["ligands"])
    kinds = {}
    softcore: dict[str, set] = {}
    for edge in net["edges"]:
        a, b = edge["source"], edge["target"]
        graph.add_edge(a, b)
        kinds[(a, b)] = edge.get("kind", "rbfe")
        mapping = edge.get("mapping") or {}
        for ligand, field in ((a, "sc1"), (b, "sc2")):
            if field in mapping:
                softcore.setdefault(ligand, set()).add(tuple(sorted(mapping[field])))

    nonuniform = sorted(name for name, masks in softcore.items() if len(masks) > 1)
    n_rejected = sum(1 for c in net.get("candidates", []) if (c.get("score") or {}).get("rejections"))
    bridges = list(nx.bridges(graph)) if graph.number_of_edges() else []
    on_cycle = {n for n in graph.nodes if any(n in c for c in nx.cycle_basis(graph))}
    edge_on_cycle = sum(1 for a, b in graph.edges if (a, b) not in bridges and (b, a) not in bridges)
    return {
        "n_bridges": len(bridges),
        "node_cycle_coverage": len(on_cycle) / graph.number_of_nodes() if graph.number_of_nodes() else 0.0,
        "edge_cycle_coverage": edge_on_cycle / graph.number_of_edges() if graph.number_of_edges() else 0.0,
        "n_components": nx.number_connected_components(graph),
        "hub": max(dict(graph.degree).items(), key=lambda kv: kv[1])[0] if graph.number_of_edges() else None,
        "n_cbfe_edges": sum(1 for k in kinds.values() if k != "rbfe"),
        "n_rejected": n_rejected,
        "n_nonuniform_softcore": len(nonuniform),
        "nonuniform_softcore": nonuniform,
    }


def run_matrix(ligands: list[Path], out: Path, jobs: int) -> list[dict]:
    """Plan every variant and return one metrics record per variant.

    A variant that fails to plan is recorded with an ``error`` key rather than aborting
    the run: one bad flag combination should not cost the other twenty.
    """
    cli = [sys.executable, "-m", "rbfenetmap.cli.main"]
    results = []
    for key, section, label, flags, extra_exports in VARIANTS:
        vdir = out / key
        vdir.mkdir(parents=True, exist_ok=True)
        net = vdir / "network.json"
        exporters = ["html", "json", "edgelist", "graphml", *extra_exports]
        cmd = [
            *cli,
            "plan",
            "--ligands",
            *[str(p) for p in ligands],
            "--jobs",
            str(jobs),
            "--out",
            str(net),
            "--export",
            *exporters,
            "--export-dir",
            str(vdir),
            *flags,
        ]
        started = time.time()
        proc = subprocess.run(cmd, capture_output=True, text=True)
        elapsed = time.time() - started

        record = {
            "key": key,
            "section": section,
            "label": label,
            "flags": " ".join(flags) or "(defaults)",
            "seconds": round(elapsed, 1),
        }
        if proc.returncode != 0 or not net.exists():
            tail = (proc.stderr or proc.stdout).strip().splitlines()
            record["error"] = tail[-1] if tail else "failed"
            print(f"FAIL {key}: {record['error']}")
            results.append(record)
            continue

        (vdir / "plan.stdout.txt").write_text(proc.stdout)
        diag = subprocess.run(
            [*cli, "diagnose", "--network", str(net), "--seed", SEED, "--format", "json"],
            capture_output=True,
            text=True,
        )
        record.update(json.loads(diag.stdout))
        (vdir / "diagnose.json").write_text(diag.stdout)
        table = subprocess.run(
            [*cli, "diagnose", "--network", str(net), "--seed", SEED, "--format", "table"],
            capture_output=True,
            text=True,
        )
        (vdir / "diagnose.txt").write_text(table.stdout)
        record.update(graph_metrics(net))
        results.append(record)
        print(f"ok   {key}: {record['n_edges']} edges, cost {record['cost']:.2f}, {elapsed:.1f}s")
    return results


