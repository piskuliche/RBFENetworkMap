def main() -> int:
    """Plan every variant, then render the index over them."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out", type=Path, help="Directory to write the variant reports into.")
    parser.add_argument(
        "--ligands",
        type=Path,
        nargs="+",
        default=None,
        help=f"Ligand files or a directory. Defaults to the shipped Tyk2 series in {DATA}.",
    )
    parser.add_argument("--jobs", type=int, default=8, help="Worker processes per plan (default: 8).")
    parser.add_argument(
        "--index-only", action="store_true", help="Skip planning and rebuild index.html from an existing matrix.json."
    )
    args = parser.parse_args()

    paths = args.ligands or [DATA]
    ligands = sorted(p for root in paths for p in ([root] if root.is_file() else sorted(root.glob("*.mol2"))))
    if not ligands:
        parser.error(f"no ligand files found in {[str(p) for p in paths]}")

    args.out.mkdir(parents=True, exist_ok=True)
    matrix = args.out / "matrix.json"
    if args.index_only:
        rows = json.loads(matrix.read_text())
    else:
        print(f"Planning {len(VARIANTS)} variants over {len(ligands)} ligands into {args.out}")
        rows = run_matrix(ligands, args.out, args.jobs)
        matrix.write_text(json.dumps(rows, indent=2))

    path = build_index(rows, args.out, len(ligands))
    failed = [r["key"] for r in rows if "error" in r]
    print(f"\nwrote {path} ({len(rows)} variants)")
    if failed:
        print(f"{len(failed)} variant(s) failed to plan: {', '.join(failed)}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
